/**
 * Detects system/device language matching one of our supported languages.
 */
export const detectSystemLanguage = (): Language => {
  try {
    const rawLanguages = navigator.languages || [navigator.language || 'fr'];
    for (const lang of rawLanguages) {
      const lower = lang.toLowerCase();
      if (lower.startsWith('ht') || lower.includes('haitian') || lower.includes('kreyol')) {
        return 'ht';
      }
      if (lower.startsWith('es')) {
        return 'es';
      }
      if (lower.startsWith('en')) {
        return 'en';
      }
      if (lower.startsWith('fr')) {
        return 'fr';
      }
    }
  } catch (err) {
    console.warn('Could not detect device language, defaulting to French', err);
  }
  return 'fr';
};

export const resolveActiveLanguage = (setting: LanguageSetting): Language => {
  if (setting === 'auto') {
    return detectSystemLanguage();
  }
  return setting;
};

